#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {triageHydraulicReviewBatch,validateTriageExport} from './lib/hydraulic-editorial-triage.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const benchmark=read('data/quality/hydraulic-diagnostic-reasoning-benchmark.v1.json');
const protocol=read('data/quality/hydraulic-expert-review-protocol.v1.json');
const empty=read('data/quality/hydraulic-expert-review-sheet.v1.json');
const clone=x=>structuredClone(x);
const errors=[];let checks=0;
function expect(id,condition){checks++;if(!condition)errors.push(id)}
function rejected(id,fn){checks++;try{fn();errors.push('accepted_'+id)}catch{}}
const baseline=triageHydraulicReviewBatch(benchmark,protocol,[empty]);
expect('empty_cases',baseline.cases.length===20);
expect('all_awaiting',baseline.statusCounts.AWAITING_REVIEW===20);
expect('unverified',baseline.independentReviewerCount===null&&!baseline.engineeringApproved&&!baseline.operationalRelease&&!baseline.sapApproved);
expect('baseline_contract',validateTriageExport(baseline));
const left=clone(empty),right=clone(empty);
left.rows[0].recommendedChoiceCode=benchmark.entries[0].choices[0].code;
right.rows[0].recommendedChoiceCode=benchmark.entries[0].choices[1].code;
let result=triageHydraulicReviewBatch(benchmark,protocol,[left,right]);
expect('answer_disagreement',result.cases[0].status==='ANSWER_DISAGREEMENT');
expect('two_observations_not_independent',result.cases[0].nonIndependentAnonymousSubmissions===2&&result.independentReviewerCount===null);
left.rows[0].ratings.safety_boundary='critical_issue';
result=triageHydraulicReviewBatch(benchmark,protocol,[left,right]);
expect('safety_over_answer_disagreement',result.cases[0].status==='SAFETY_HOLD'&&result.cases[0].flags.includes('ANSWER_DISAGREEMENT'));
const good=clone(empty);
good.rows[0].recommendedChoiceCode=benchmark.entries[0].choices[0].code;
for(const key of Object.keys(good.rows[0].ratings))good.rows[0].ratings[key]='adequate';
const goodResult=triageHydraulicReviewBatch(benchmark,protocol,[good]);
expect('adequate_not_approved',goodResult.cases[0].status==='NO_ISSUE_REPORTED'&&goodResult.cases[0].independentlyApproved===false);
const alsoGood=clone(good);
result=triageHydraulicReviewBatch(benchmark,protocol,[good,alsoGood,left]);
expect('safety_over_duplicate_positive',result.cases[0].status==='SAFETY_HOLD'&&result.independentReviewerCount===null);
const tags=clone(empty);tags.rows[0].issueTags=['unsafe_action_risk'];
expect('unsafe_tag_triggers_hold',triageHydraulicReviewBatch(benchmark,protocol,[tags]).cases[0].status==='SAFETY_HOLD');
const other=clone(empty);other.rows[0].ratings.observability='critical_issue';
expect('nonsafety_critical',triageHydraulicReviewBatch(benchmark,protocol,[other]).cases[0].status==='CRITICAL_EDITORIAL_REVIEW');
const revision=clone(empty);revision.rows[0].ratings.distractor_quality='needs_revision';
expect('revision_backlog',triageHydraulicReviewBatch(benchmark,protocol,[revision]).cases[0].status==='REVISION_BACKLOG');
expect('contract_positive',validateTriageExport(result));
const bad1=clone(empty);bad1.rows[0].serialNumber='PRIVATE-SECRET';
rejected('private_field',()=>triageHydraulicReviewBatch(benchmark,protocol,[bad1]));
const bad2=clone(empty);bad2.rows[0].ratings.safety_boundary='approved';
rejected('fake_approval',()=>triageHydraulicReviewBatch(benchmark,protocol,[bad2]));
const bad3=clone(empty);bad3.rows[1].caseId=bad3.rows[0].caseId;
rejected('duplicate_case',()=>triageHydraulicReviewBatch(benchmark,protocol,[bad3]));
const bad4=clone(empty);bad4.rows[0].recommendedChoiceCode='MADE_UP';
rejected('unknown_choice',()=>triageHydraulicReviewBatch(benchmark,protocol,[bad4]));
rejected('zero_sheets',()=>triageHydraulicReviewBatch(benchmark,protocol,[]));
rejected('excess_sheets',()=>triageHydraulicReviewBatch(benchmark,protocol,Array.from({length:101},()=>empty)));
let invalid=clone(result);invalid.engineeringApproved=true;
expect('reject_approval_in_export',!validateTriageExport(invalid));
invalid=clone(result);invalid.cases[0].serialNumber='PRIVATE';
expect('reject_private_in_export',!validateTriageExport(invalid));
invalid=clone(result);invalid.cases[0].status='APPROVED';
expect('reject_invalid_status',!validateTriageExport(invalid));
invalid=clone(result);invalid.statusCounts.SAFETY_HOLD=999;
expect('reject_inconsistent_counts',!validateTriageExport(invalid));
invalid=clone(result);invalid.cases[0].dimensionCounts.safety_boundary.critical_issue=-1;
expect('reject_invalid_counts',!validateTriageExport(invalid));
invalid=clone(result);invalid.cases[0].choiceCodesObserved.push('private@company.example');
expect('reject_free_text',!validateTriageExport(invalid));
const report={schema:'fmea-mining.hydraulic-editorial-triage-audit.v1',version:'1.3.96',status:errors.length?'FAIL':'OK',checks,syntheticCases:20,anonymousRealReviewsReceived:0,sapModifications:0,operationalApprovals:0,errors};
const out=path.join(root,'reports/hydraulic-editorial-triage.generated.json');
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));process.exit(errors.length?1:0);
