#!/usr/bin/env node
/** Track idler inventory, component-role separation and CTS gates. No field evidence. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {inspectIdlerScope,validateIdlerScope,classifyIdlerPart,IDLER_ROLES} from './lib/pm-idler-scope.mjs';
import {inspectFocusGuards} from './lib/pm-functional-boundaries.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const db=read('data/catalog/failure-db.v1.json');
const seed=read('data/knowledge/pm-prevention/seed-rules.json').records;
const gaps=read('data/quality/pm-gap-review.v1.json').records;
const gates=read('data/quality/pm-exception-evidence-gates.v1.json').records;
const links=read('data/knowledge/pm-prevention/generated-links.json').records;
const semantic=read('data/ontology/condition-action-damage.v1.json');
const sources=read('data/research/sources.v1.json').sources;
const review=read('data/quality/pm-idler-technical-review.v1.json');
const errors=[...inspectFocusGuards(seed,gaps,gates,links)],check=(yes,id)=>{if(!yes)errors.push(id)};
const rule=seed.find(x=>x.id==='track-idler-wear'),gap=gaps.find(x=>x.ruleId===rule?.id),gate=gates.find(x=>x.ruleId===rule?.id);
check(!!rule&&!!gap&&!!gate,'missing_idler_rule_review_or_gate');
check(rule?.subgroupCode==='IDLE'&&rule?.partText==='Rolamento'&&rule?.damageId==='02.01'&&rule?.causeId==='C1.04','idler_rule_drift');
check(gap?.expectedBlocker==='component_not_registered'&&gap.status==='bloqueado_aguardando_curadoria'&&gap.autoRemapAllowed===false&&gap.observedFailures===0,'idler_gap_promoted');
check(gate?.sourceBlocker==='component_not_registered'&&gate.requiredSubgroup==='IDLE'&&gate.reviewedByEngineering===false&&gate.confirmedFailureEvent===false&&gate.approvedLocationId===null&&gate.approvedComponentCode===null&&gate.proposedPartNumber===null&&gate.autogeneratedRemapAllowed===false,'idler_gate_promoted');
check(!links.some(x=>x.originRule===rule.id),'idler_link_generated_without_review');
const report=inspectIdlerScope(db,rule);errors.push(...validateIdlerScope(report,db,rule));
check(report.idler.summary.bearingTextOccurrences===0,'bearing_in_IDLE_changed');
check(report.idler.summary.bearingDamageCauseEligibleOccurrences===0,'new_IDLER_bearing_match');
check(review?.schema==='fmea-mining.pm-idler-technical-review.v1'&&review.version==='1.3.41'&&review.target.ruleId===rule.id&&review.target.subgroup===rule.subgroupCode&&review.target.damageId===rule.damageId&&review.target.causeId===rule.causeId,'review_header_drift');
check(review.reviewNature==='catalogue_and_oem_general_technical_requirements_not_real_inspection','review_claims_field');
check(review.receivedDocuments===0&&review.recordedInspections===0&&review.confirmedFailures===0&&review.approvedMappings===0,'invented_review_events');
check(review.differentialModes.length===4&&review.necessaryEvidence.length===6&&review.crossComponentOntologyRefs.length===2,'incomplete_evidence_matrix');
check(Object.keys(review.publicationRules).length===9&&Object.values(review.publicationRules).every(x=>x===true),'dangerous_publication_rule');
const sourceIds=new Set(sources.map(x=>x.id));
check(review.sourceIds.length===4&&review.sourceIds.every(x=>sourceIds.has(x)),'unregistered_cat_or_sap_sources');
const bundle=semantic.bundles.find(x=>x.ruleId===rule.id);
check(bundle?.mappingScope==='generic_only'&&bundle.automaticDamagePromotion===false&&bundle.confirmedDamageIds.length===0&&bundle.observedConditionIds.length===0&&bundle.performedActionIds.length===0,'idler_semantics_promoted');
check(bundle?.conditionIds.includes('COND-TRACK-IDLER-WEAR')&&bundle.conditionIds.includes('COND-TRACK-ROLLER-HEAT'),'unexpected_idler_bundle_conditions');
check(bundle?.actionIds.includes('ACT-TRACK-IDLER-CTS')&&bundle.actionIds.includes('ACT-TRACK-ROLLER-SEAL-CHECK'),'unexpected_idler_bundle_actions');
check(bundle?.differentialDamageIds.includes('DMG-TRACK-IDLER-WEAR'),'missing_idler_differential');
check(review.crossComponentOntologyRefs.some(x=>x.refId==='COND-TRACK-ROLLER-HEAT'&&x.decision==='reference_only_not_idler_observation')&&
 review.crossComponentOntologyRefs.some(x=>x.refId==='ACT-TRACK-ROLLER-SEAL-CHECK'&&x.decision==='review_action_scope_before_training_or_execution'),'roller_borrowing_not_disclosed');
for(const id of bundle.conditionIds){
 const c=semantic.conditions.find(x=>x.id===id);
 check(c?.status==='condition_hypothesis_not_observed'&&c.observedValue===null&&c.observedAt===null,'false_condition_observed_'+id);
}
for(const id of bundle.actionIds){
 const a=semantic.actions.find(x=>x.id===id);
 check(a?.executionStatus==='not_performed'&&a.requiresApplicableOemProcedure===true&&a.observedResults.length===0&&a.intervalHours===null,'false_cts_execution_'+id);
}
for(const id of bundle.differentialDamageIds){
 const d=semantic.damageHypotheses.find(x=>x.id===id);
 check(d?.confirmed===false&&d.reviewStatus==='not_approved'&&Object.values(d.catalogMapping).every(v=>v===null),'false_idler_damage_confirmation_'+id);
}
for(const m of review.differentialModes){
 check(typeof m.question==='string'&&m.question.length>=70&&m.alternative.length>=70&&m.verification.length>=70,'poor_differential_'+m.id);
}
for(const e of review.necessaryEvidence)check(e.proof.length>=70&&e.restriction.length>=50,'weak_CTS_gate_'+e.id);

const loc=(model,system,group,sub,obj)=>({modelo:model,profundidade:3,sistema:{codigo:system},grupo:{codigo:group},subgrupo:{codigo:sub},objetoTipoSAP:obj});
const fake={
 locations:[
  loc('T1','UNCR','TRCK','IDLE','IDL'),
  loc('T1','UNCR','TRCK','ROLL','ROL'),
  loc('T1','UNCR','TRCK','BEAR','BRC'),
  loc('T1','DRTR','TRCK','IDLE','BRC'),
  loc('T2','UNCR','TRCK','IDLE','BRC')],
 partsByObjectType:{
  IDL:[{code:'I-W',pt:'Roda-guia dianteira'},{code:'I-A',pt:'Eixo da roda-guia'},{code:'I-V',pt:'Vedação'},{code:'I-B',pt:'Bucha de apoio'}],
  ROL:[{code:'R-L',pt:'Rolamento do rolete'},{code:'R-R',pt:'Rolete'}],
  BRC:[{code:'B-1',pt:'Rolamento'}]
 },
 compatibleFailureModesByPart:{'R-L':{damageCauses:{'02.01':['C1.04']}},'B-1':{damageCauses:{'02.01':['C1.04']}}}
};
const fakeRule={...rule,models:['T1']};
const fixture=inspectIdlerScope(fake,fakeRule);
check(fixture.counts.idleLeafPaths===1&&fixture.counts.uncrLeafPaths===3&&fixture.counts.modelLeafPaths===4,'incorrect_model_or_root_guard');
check(fixture.idler.summary.bearingTextOccurrences===0&&fixture.idler.summary.idlerWheelTextOccurrences===2,'false_idler_bearing_inference');
check(fixture.idler.summary.bushingTextOccurrences===1&&fixture.idler.summary.sealTextOccurrences===1,'missing_bushing_or_seal_class');
check(fixture.otherUndercarriage.summary.bearingTextOccurrences===2&&fixture.otherUndercarriage.summary.bearingDamageCauseEligibleOccurrences===2,'cross_subgroup_bearing_not_found');
check(validateIdlerScope(fixture,fake,fakeRule).length===0,'synthetic_baseline_rejected');
const lexical=[
 ['Rolamento','bearing'],['Bearing','bearing'],['Roda-guia','idler_wheel'],
 ['Idler Wheel','idler_wheel'],['Retentor','seal'],['Vedação','seal'],
 ['Bucha','bushing'],['Eixo','axle'],['Rolete','roller'],['Guia','guide_generic']
];
for(const [s,role] of lexical)check(classifyIdlerPart(s).includes(role),'lexical_role_missed_'+role);
check(classifyIdlerPart('Rolete').every(x=>x!=='bearing'&&x!=='idler_wheel'),'roller_falsely_idler_bearing');
check(classifyIdlerPart('Roda-guia').every(x=>x!=='bearing'),'wheel_falsely_bearing');
check(classifyIdlerPart('Bucha de apoio').every(x=>x!=='bearing'),'bushing_falsely_bearing');
const clone=x=>JSON.parse(JSON.stringify(x));
const attacks=[
 x=>{x.installedBearingConfirmed=true;},
 x=>{x.internalBearingFailureConfirmed=true;},
 x=>{x.ctsMeasuredWearPercent=96;},
 x=>{x.confirmedSealLeak=true;},
 x=>{x.proposedSapRemapApproved=true;},
 x=>{x.independentReviewCompleted=true;},
 x=>{x.generatedWorkOrders=1;},
 x=>{x.originalSubgroup='ROLL';},
 x=>{x.idler.summary.bearingTextOccurrences=1;},
 x=>{x.counts.idleLeafPaths=99;},
 x=>{x.idler.branches[0].evidence='installed_bearing_oem_confirmed';},
 x=>{x.otherUndercarriage.bearingTextBranches.pop();},
 x=>{x.models=['WRONG'];},
 x=>{x.idler.branches[0].roleOccurrences.bearing=10;}
];
let rejected=0;
for(const change of attacks){const v=clone(fixture);change(v);if(validateIdlerScope(v,fake,fakeRule).length)rejected++;else errors.push('adversarial_mutation_accepted_'+rejected);}
check(rejected===attacks.length,'mutation_suite_incomplete');
const result={...report,engineeringReview:{
 scope:'external_idler_wear_vs_bearing_vs_seal_vs_alignment',
 differentialModes:review.differentialModes,
 evidenceRequirements:review.necessaryEvidence,
 crossComponentOntologyRefs:review.crossComponentOntologyRefs,
 notes:'Roller heat and roller seal task in idler semantic bundle are not measurements or repairs of idler; require independent review.',
 ctsFieldMeasurements:0,inspectionsExecuted:0,installedBearingValidated:false,sapMappingApproved:false},
 audit:{lexicalCases:lexical.length,syntheticGeometryCases:5,unsafeMutationsRejected:rejected,
 seedRules:seed.length,generatedCandidateLinks:links.length,pmExceptionsBlocked:gaps.length,
 observedFailures:0,performedActions:0},errors};
fs.mkdirSync(path.join(root,'reports'),{recursive:true});
fs.writeFileSync(path.join(root,'reports/pm-idler-scope.generated.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({status:errors.length?'FAIL':'OK',
 counts:report.counts,idler:report.idler.summary,siblingUndercarriage:report.otherUndercarriage.summary,
 siblingBearingCandidates:report.otherUndercarriage.bearingTextBranches.map(g=>({system:g.systemCode,group:g.groupCode,subgroup:g.subgroupCode,
 models:g.models,occurrences:g.roleOccurrences.bearing,uniqueCodesWithinTypes:g.uniqueCodesByRoleWithinType.bearing,
 allowedDamageCause:g.bearingDamageCauseEligibleOccurrences})),
 crossComponentRefs:review.crossComponentOntologyRefs.map(x=>x.refId),
 lexicalCases:lexical.length,unsafeMutationsRejected:rejected,errors},null,2));
process.exit(errors.length?1:0);
