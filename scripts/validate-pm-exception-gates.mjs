#!/usr/bin/env node
/** Valida criticamente dez exceções PM e sete documentos do piloto D9, com 16 mutações sintéticas. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {inspectPm,inspectD9} from './lib/pm-exception-gates.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const gate=read('data/quality/pm-exception-evidence-gates.v1.json');
const d9=read('data/quality/oem-d9-evidence-intake.v1.json');
const review=read('data/quality/pm-gap-review.v1.json');
const rules=read('data/knowledge/pm-prevention/seed-rules.json');
const generated=read('reports/pm-gap-audit.generated.json');
const pilot=read('data/quality/oem-pilot-readiness.v1.json');
const sources=new Set(read('data/research/sources.v1.json').sources.map(x=>x.id));
const fixtures=read('data/quality/pm-exception-regressions.v1.json');
const errors=[],ck=(x,s)=>{if(!x)errors.push(s);};
ck(gate.schema==='fmea-mining.pm-exception-evidence-gates.v1'&&gate.version==='1.3.16'&&gate.nature==='editorial_hypotheses_not_oem_effectivity','Registro PM incorreto');
ck(gate.counts.blockedRules===10&&gate.counts.unresolvedGates===10&&gate.counts.systemicProcessOrComponentApprovals===0,'Contagem/causas PM indevidas');
ck(gate.policy.expectedBlockedRules===10&&Object.entries(gate.policy).filter(([key])=>key!=='expectedBlockedRules').every(([,value])=>value===true),'Política PM relaxada');
ck(d9.schema==='fmea-mining.oem-d9-evidence-intake.v1'&&d9.version==='1.3.16','Registro D9 inválido');
ck(generated.summary.withoutStrictCandidates===10&&generated.summary.approvedEngineeringLinks===0,'Auditoria de entrada PM mudou');
errors.push(...inspectPm(gate.records,review,rules,generated,sources));
errors.push(...inspectD9(d9,pilot,sources));
ck(fixtures.schema==='fmea-mining.pm-exception-regressions.v1'&&fixtures.version==='1.3.16'&&fixtures.nature==='synthetic_only'&&fixtures.cases.length===16,'Fixtures de regressão ausentes');
const copy=x=>JSON.parse(JSON.stringify(x));
const mutations={
 none:()=>{},
 allowAutoRemap:(x)=>{x.records[0].autogeneratedRemapAllowed=true},
 approveLocation:(x)=>{x.records[0].approvedLocationId='FAKE-SAP-LOC'},
 approveCause:(x)=>{x.records[0].confirmedFailureEvent=true},
 inventPartNumber:(x)=>{x.records[0].proposedPartNumber='FAKE-PART'},
 removeEvidence:(x)=>{x.records[0].minimumEvidence.pop()},
 removeAlternative:(x)=>{x.records[0].independentAlternative=''},
 changeBlocker:(x)=>{x.records[0].sourceBlocker='component_not_registered'},
 duplicateRule:(x)=>{x.records.push(copy(x.records[0]))},
 inventSerial:(x)=>{x.requiredInputs[0].sourceValue='FAKE-D9-SERIAL'},
 approvePilot:(x)=>{x.pilotOperationallyApproved=true},
 inventLimit:(x)=>{x.measurementLimitsVerified=true},
 removeInput:(x)=>{x.requiredInputs.pop()},
 approveChecklist:(x)=>{x.requiredInputs[0].approved=true},
 removeChain:(x)=>{x.relatedChainIds.pop()}
};
const used=new Set();
for(const t of fixtures.cases){
 ck(!used.has(t.id),'Teste repetido '+t.id);used.add(t.id);
 ck(typeof mutations[t.mutation]==='function','Mutação desconhecida '+t.id);
 if(!mutations[t.mutation])continue;
 const cloned=copy(t.target==='pm'?gate:d9);
 mutations[t.mutation](cloned);
 const failures=t.target==='pm'?inspectPm(cloned.records,review,rules,generated,sources):inspectD9(cloned,pilot,sources);
 const status=failures.length?'reject':'pass';
 ck(t.expected===status,'Gate de mutação falhou '+t.id+' esperado '+t.expected+' recebido '+status);
}
const summary={status:errors.length?'FAIL':'OK',pmRulesAudited:gate.records.length,blockers:{subgroup:3,component:5,damageCause:2},approvedRemaps:0,d9DocumentationGaps:d9.requiredInputs.length,verifiedOemEffectivity:0,fieldEvidence:0,syntheticRegressions:fixtures.cases.length,errors:errors.slice(0,30)};
console.log(JSON.stringify(summary,null,2));process.exit(errors.length?1:0);
