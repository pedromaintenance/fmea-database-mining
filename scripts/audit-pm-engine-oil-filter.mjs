#!/usr/bin/env node
/** Actual engine-oil filter gap scan + adversarial catalogue/object-type tests. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {examineEngineOilFilterScope,validateEngineOilReport,classifyOilFilterText,EVIDENCE_IDS,ACTION_IDS,DAMAGE_ID} from './lib/pm-engine-oil-filter-scope.mjs';
import {inspectFocusGuards} from './lib/pm-functional-boundaries.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const db=read('data/catalog/failure-db.v1.json');
const seed=read('data/knowledge/pm-prevention/seed-rules.json').records;
const gaps=read('data/quality/pm-gap-review.v1.json').records;
const gates=read('data/quality/pm-exception-evidence-gates.v1.json').records;
const links=read('data/knowledge/pm-prevention/generated-links.json').records;
const semantic=read('data/ontology/condition-action-damage.v1.json');
const sources=read('data/research/sources.v1.json').sources;
const errors=[...inspectFocusGuards(seed,gaps,gates,links)],check=(ok,id)=>{if(!ok)errors.push(id)};
const rule=seed.find(r=>r.id==='engine-oil-filter');
const gap=gaps.find(x=>x.ruleId===rule?.id);
const gate=gates.find(x=>x.ruleId===rule?.id);
check(Boolean(rule&&gap&&gate),'missing_blocked_engine_oil_rule');
check(rule?.subgroupCode==='LUSY'&&rule?.damageId==='03.02'&&rule?.causeId==='C2.09','engine_oil_rule_changed');
check(gap?.expectedBlocker==='component_not_registered'&&gap?.status==='bloqueado_aguardando_curadoria'&&gap.autoRemapAllowed===false,'engine_oil_exception_promoted');
check(gate?.sourceBlocker==='component_not_registered'&&gate?.decision==='manter_bloqueado_sem_evidencia'&&
  gate.autogeneratedRemapAllowed===false&&gate.reviewedByEngineering===false&&
  gate.approvedLocationId===null&&gate.approvedComponentCode===null&&gate.proposedPartNumber===null,'evidence_gate_fabricated');
check(!links.some(x=>x.originRule===rule.id),'engine_filter_received_unreviewed_links');
const result=examineEngineOilFilterScope(db,rule);
errors.push(...validateEngineOilReport(result,db,rule));
check(result.targetSubgroup.summary.matchedLeafPaths===0&&result.targetSubgroup.summary.matchedDescriptionOccurrences===0,'unreviewed_LUSY_component_promotion');
check(result.originalGroup==='ENGN'&&result.originalSubgroup==='LUSY','wrong_original_scope');
const bundle=semantic.bundles.find(x=>x.ruleId===rule.id);
check(semantic.safetyInvariant==='condition!=action!=damage'&&semantic.evidenceNature==='no_field_observation','semantic_invariant_drift');
check(bundle?.mappingScope==='generic_only'&&bundle.automaticDamagePromotion===false&&bundle.confirmedDamageIds.length===0,'engine_filter_damage_promoted');
check(EVIDENCE_IDS.every(id=>bundle?.conditionIds.includes(id))&&ACTION_IDS.every(id=>bundle?.actionIds.includes(id))&&
  bundle?.differentialDamageIds.includes(DAMAGE_ID),'missing_engine_diagnostic_differentials');
const ontologyStates=EVIDENCE_IDS.map(id=>{
 const c=semantic.conditions.find(x=>x.id===id);
 check(c?.status==='condition_hypothesis_not_observed'&&c?.observedValue===null&&c?.observedAt===null,'observed_hypothesis_'+id);
 return {id,observationState:'not_observed'};
});
for(const id of ACTION_IDS){
 const a=semantic.actions.find(x=>x.id===id);
 check(a?.executionStatus==='not_performed'&&a.requiresApplicableOemProcedure===true&&a.intervalHours===null,'unsafe_or_performed_test_'+id);
}
const damage=semantic.damageHypotheses.find(x=>x.id===DAMAGE_ID);
check(damage?.confirmed===false&&damage?.reviewStatus==='not_approved'&&Object.values(damage.catalogMapping).every(v=>v===null),'damage_coded_as_confirmed');
const sourceIds=new Set(sources.map(x=>x.id));
check(['CAT-ENGINE-OIL-FILTER-SERVICE','SAP-FUNCTIONAL-LOCATION-STRUCTURE','CAT-FILTERS-FLUIDS-GUIDE'].every(x=>sourceIds.has(x)),'missing_primary_source');
const place=(m,root,group,sub,type)=>({profundidade:3,modelo:m,sistema:{codigo:root},grupo:{codigo:group},subgrupo:{codigo:sub},objetoTipoSAP:type});
const syntheticRule={...rule,models:['T1'],subgroupCode:'LUSY'};
const fixture={
 locations:[
  place('T1','ENSY','ENGN','LUSY','LUBE'),
  place('T1','ENSY','ENGN','FILR','FILTER'),
  place('T1','ENSY','FUSY','HSVV','FUEL'),
  place('T1','HYSY','ENGN','LUSY','FILTER'),
  place('T2','ENSY','ENGN','FILR','FILTER'),
  place('T1','ENSY','ENGN','OILS','OTHER')
 ],
 partsByObjectType:{
  LUBE:[{code:'L-1',pt:'Tampa de lubrificação'}],
  FILTER:[{code:'F-1',pt:'Filtro de óleo do motor'},{code:'F-2',pt:'Filtro genérico'}],
  FUEL:[{code:'F-3',pt:'Filtro combustível'}],
  OTHER:[{code:'X-1',pt:'Bomba de óleo'}]
 },
 compatibleFailureModesByPart:{
  'F-1':{damageCauses:{'03.02':['C2.09']}},
  'F-2':{damageCauses:{'03.02':['C2.08']}}
 }
};
const f=examineEngineOilFilterScope(fixture,syntheticRule);
check(f.targetSubgroup.summary.matchedDescriptionOccurrences===0,'synthetic_wrong_LUSY_match');
check(f.sameEngineGroupOtherSubgroups.summary.matchedLeafPaths===1&&
 f.sameEngineGroupOtherSubgroups.summary.matchedDescriptionOccurrences===2&&
 f.sameEngineGroupOtherSubgroups.summary.eligibleDamageCauseOccurrences===1,'synthetic_wrong_sibling_subgroup_discovery');
check(f.outsideEngineGroup.summary.matchedLeafPaths===1&&f.outsideEngineGroup.branches.every(x=>x.groupCode!=='ENGN'),'synthetic_fuel_cross_link');
check(f.counts.engineGroupLeafPaths===3&&f.counts.targetLusyLeafPaths===1,'synthetic_scope_not_strict');
check(validateEngineOilReport(f,fixture,syntheticRule).length===0,'synthetic_baseline_invalid');
const classes=[
 ['Filtro de óleo','oil_filter_text'],['Filtro Diesel','fuel_filter_text'],
 ['Filtro de ar','air_filter_text'],['Filtro hidráulico','hydraulic_filter_text'],
 ['Filtro','unqualified_filter_text'],['Elemento filtrante','unqualified_filter_text'],
 ['Tampa de lubrificação','not_explicit_filter_text'],
 ['Bomba de óleo','not_explicit_filter_text'],
 ['Filtro do ar e óleo','ambiguous_filter_media']
];
for(const [description,expected] of classes)check(classifyOilFilterText(description)===expected,'lexical_false_class_'+expected);
const clone=x=>JSON.parse(JSON.stringify(x));
const mutations=[
 x=>{x.installedPartConfirmed=true},
 x=>{x.proposedRemapApproved=true},
 x=>{x.newCatalogPartCreated=true},
 x=>{x.verifiedOemEffectivity=true},
 x=>{x.confirmedFailureEvents=1},
 x=>{x.originalSubgroup='FILR'},
 x=>{x.targetSubgroup.summary.matchedDescriptionOccurrences=1},
 x=>{x.sameEngineGroupOtherSubgroups.branches.push(x.targetSubgroup.branches[0])},
 x=>{x.counts.modelLeafPaths=0},
 x=>{x.outsideEngineGroup.summary.eligibleDamageCauseOccurrences=777},
 x=>{x.classification='OEM_effective_by_serial'},
 x=>{x.modelCount=999},
 x=>{x.targetSubgroup.branches[0].disposition='approved_installed_oil_filter'}
];
let rejected=0;
for(let i=0;i<mutations.length;i++){
 const fake=clone(f);mutations[i](fake);
 if(validateEngineOilReport(fake,fixture,syntheticRule).length)rejected++;
 else errors.push('adversarial_mutation_accepted_'+i);
}
check(rejected===mutations.length,'mutation_check_incomplete');
const report={...result,semanticEvidence:{
 separationInvariant:'low_engine_oil_pressure_does_not_prove_filter_restriction',
 differentialPressureCondition:EVIDENCE_IDS[0],
 alternativeConditions:EVIDENCE_IDS.slice(1),
 proposedActions:ACTION_IDS,componentDamageHypothesis:DAMAGE_ID,
 conditionStates:ontologyStates,
 maintenanceExecution:'none',independentOEMTest:'not_performed',
 evidenceReceived:0,approvedDamageMappings:0
},audit:{regressionTextCases:classes.length,unsafeReportMutationsRejected:rejected,
 catalogueRules:seed.length,generatedCandidateLinks:links.length,blockedPmRules:gaps.length,
 observations:0,approvedSapMappings:0},errors};
fs.mkdirSync(path.join(root,'reports'),{recursive:true});
fs.writeFileSync(path.join(root,'reports/pm-engine-oil-filter-scope.generated.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({status:errors.length?'FAIL':'OK',
 counts:result.counts,targetSubgroup:result.targetSubgroup.summary,
 siblingEngine:result.sameEngineGroupOtherSubgroups.summary,
 siblingCandidates:result.sameEngineGroupOtherSubgroups.branches.map(x=>({group:x.groupCode,subgroup:x.subgroupCode,
  models:x.models,descriptionOccurrences:x.descriptorMatchesPerPath,compatiblePairs:x.damageCauseEligibleMatchesPerPath,
  hints:x.lexicalHints})),
 otherEngineGroups:result.outsideEngineGroup.summary,
 lexicalCases:classes.length,adversarialMutationsRejected:rejected,errors},null,2));
process.exit(errors.length?1:0);
