// Gates independentes de dados; não transformam hipóteses SAP/OEM em dados de campo.
export function inspectPm(records, sourceReview, rules, generatedAudit, sources){
 const errors=[];const ck=(ok,msg)=>{if(!ok)errors.push(msg);};
 const reference=new Map(sourceReview.records.map(x=>[x.ruleId,x]));
 const seeds=new Map(rules.records.map(x=>[x.id,x]));
 const auditIndex=new Map(generatedAudit.records.map(x=>[x.ruleId,x]));
 ck(records.length===10&&new Set(records.map(x=>x.ruleId)).size===10,'Conjunto PM != 10 IDs unicos');
 const domains=new Set(['condition_versus_damage','component_inventory','functional_misclassification','scope_collision','hierarchy_level_confusion']);
 for(const r of records){
  const old=reference.get(r.ruleId),seed=seeds.get(r.ruleId),audit=auditIndex.get(r.ruleId);
  ck(!!old&&!!seed&&!!audit,'Regra não encontrada '+r.ruleId);
  if(!old||!seed||!audit)continue;
  ck(r.priority===old.priority&&r.sourceBlocker===old.expectedBlocker&&audit.firstBlocker===r.sourceBlocker,'Bloqueador/priority adulterado '+r.ruleId);
  ck(audit.counts.generatedCandidateLinks===0&&audit.engineeringReviewed===false&&audit.acceptedLocations===0,'Vínculo PM gerado ou aprovado indevidamente '+r.ruleId);
  ck(r.functionUnderReview===seed.system&&r.requiredSubgroup===seed.subgroupCode&&r.requestedPartText===seed.partText&&r.requestedDamageId===seed.damageId&&r.requestedCauseId===seed.causeId,'Metadados da regra divergentes '+r.ruleId);
  ck(domains.has(r.domain)&&r.physicalMechanismToDiscriminate?.length>=65,'Discriminação física insuficiente '+r.ruleId);
  ck(r.minimumEvidence?.length===2&&r.minimumEvidence.every(x=>typeof x==='string'&&x.length>=60),'Evidências mínimas insuficientes '+r.ruleId);
  ck(typeof r.independentAlternative==='string'&&r.independentAlternative.length>=55,'Explicação alternativa insuficiente '+r.ruleId);
  ck(typeof r.proposedEditorialTreatment==='string'&&r.proposedEditorialTreatment.length>=65,'Ação editorial vaga '+r.ruleId);
  ck(r.decision==='manter_bloqueado_sem_evidencia'&&r.status==='investigacao_documental_proposta','Aprovação fictícia '+r.ruleId);
  ck(r.proposedNewSapCode===null&&r.proposedPartNumber===null&&r.approvedLocationId===null&&r.approvedComponentCode===null,'PN ou local inventado '+r.ruleId);
  ck(r.confirmedFailureEvent===false&&r.autogeneratedRemapAllowed===false&&r.reviewedByEngineering===false,'Remapeamento ou evidência fictícia '+r.ruleId);
  ck(JSON.stringify(r.sourcesGeneral)===JSON.stringify(old.sourceIds)&&r.sourcesGeneral.every(id=>sources.has(id)),'Fontes inconsistentes '+r.ruleId);
 }
 ck([...reference.keys()].every(id=>records.some(x=>x.ruleId===id)),'Alguma exceção não avaliada');
 ck(records.filter(x=>x.sourceBlocker==='subgroup_not_in_scope').length===3,'Subgrupo escopo mudou');
 ck(records.filter(x=>x.sourceBlocker==='component_not_registered').length===5,'Componentes ausentes mudaram');
 ck(records.filter(x=>x.sourceBlocker==='damage_cause_not_permitted').length===2,'Dano/causa mudou');
 return errors;
}
export function inspectD9(d9,pilot,sources){
 const errors=[];const ck=(ok,msg)=>{if(!ok)errors.push(msg);};
 ck(d9.pilotId===pilot.pilotId&&d9.modelId===pilot.candidateCatalogModel,'Piloto/modelo inconsistentes');
 ck(d9.stage==='documentary_preparation_only'&&d9.technicalReadiness==='blocked_pending_input','Piloto passou sem documentação');
 ck(d9.independentReviewStatus==='not_performed'&&d9.pilotOperationallyApproved===false&&d9.serialEffectivityVerified===false&&d9.measurementLimitsVerified===false&&d9.boltingProcedureVerified===false,'Aprovação OEM fictícia');
 ck(JSON.stringify(d9.relatedChainIds)===JSON.stringify(pilot.relatedChainIds)&&d9.relatedChainIds.length===8,'Cadeias do D9 alteradas');
 ck(JSON.stringify(d9.sourceIds)===JSON.stringify(pilot.publiclyReviewedSources)&&d9.sourceIds.every(id=>sources.has(id)),'Fontes OEM inconsistentes');
 ck(d9.expectedInputs===7&&d9.requiredInputs?.length===7&&new Set(d9.requiredInputs.map(x=>x.id)).size===7,'Requisitos OEM incompletos');
 for(const source of pilot.requiredInputs){
  const row=d9.requiredInputs.find(x=>x.id===source.id);
  ck(!!row,'Evidência D9 ausente '+source.id);if(!row)continue;
  ck(row.sourceStatus===source.status&&row.sourceValue===null&&source.value===null,'Série/documento inventado '+source.id);
  ck(row.documentReference===null&&row.verifiedBy===null&&row.approved===false,'Documento ou revisão artificial '+source.id);
  ck(row.primaryEvidence?.length>=65&&row.independentCrossCheck?.length>=65&&row.responsibleDiscipline?.length>=8,'Definição de evidência D9 insuficiente '+source.id);
 }
 const p=d9.preservation;
 ck(p?.noSpecificSerialInvented===true&&p.noTorqueValueGuessed===true&&p.noCTSLimitsGuessed===true&&p.noOEMManualPublished===true&&p.noSapMappingApproved===true,'Restrições de OEM comprometidas');
 return errors;
}
