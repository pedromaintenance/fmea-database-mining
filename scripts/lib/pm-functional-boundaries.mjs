/** Catalogued functional path != OEM/installed component validation. */
import {matchesRoot} from '../pm-system-scope.mjs';
export const FOCUS_RULES=Object.freeze([
 {id:'hydraulic-hose-leak',subgroup:'HSVV',blocker:'subgroup_not_in_scope'},
 {id:'hydraulic-hose-abrasion',subgroup:'HSVV',blocker:'subgroup_not_in_scope'},
 {id:'fuel-filter-contamination',subgroup:'HSVV',blocker:'component_not_registered'},
 {id:'drill-compressor-filter',subgroup:'COMR',blocker:'subgroup_not_in_scope'}
]);
export function classifyPmPath(rule,location){
 if(location?.profundidade!==3)return 'not_leaf_location';
 if(!rule?.models?.includes(location.modelo))return 'model_out_of_scope';
 if(!matchesRoot(rule,location))return 'system_group_out_of_scope';
 if(location.subgrupo?.codigo!==rule.subgroupCode)return 'subgroup_out_of_scope';
 return 'candidate_path';
}
export function inspectFocusGuards(rules,reviews,gates,links){
 const errors=[],byId=(records)=>new Map(records.map(x=>[x.ruleId||x.id,x]));
 const rs=byId(rules),review=byId(reviews),evidence=byId(gates);
 for(const f of FOCUS_RULES){
  const r=rs.get(f.id),v=review.get(f.id),e=evidence.get(f.id);
  if(!r||r.subgroupCode!==f.subgroup)errors.push('seed_drift_'+f.id);
  if(!v||v.expectedBlocker!==f.blocker||v.status!=='bloqueado_aguardando_curadoria'||v.autoRemapAllowed!==false||v.observedFailures!==0||v.approvedModelIds?.length!==0||v.confirmedSapLocationIds?.length!==0||v.verifiedPartCodes?.length!==0)errors.push('gap_unblocked_'+f.id);
  if(!e||e.sourceBlocker!==f.blocker||e.requiredSubgroup!==f.subgroup||e.decision!=='manter_bloqueado_sem_evidencia'||e.autogeneratedRemapAllowed!==false||e.reviewedByEngineering!==false||e.confirmedFailureEvent!==false||e.approvedLocationId!==null||e.approvedComponentCode!==null||e.proposedPartNumber!==null||e.proposedNewSapCode!==null)errors.push('evidence_gate_promoted_'+f.id);
  if(links.some(l=>l.originRule===f.id))errors.push('blocked_rule_generated_link_'+f.id);
 }
 return errors;
}
export function catalogueBranches(locations,rule){
 const collected=new Map();
 for(const l of locations){
  if(l.profundidade!==3||!rule.models.includes(l.modelo))continue;
  if(rule.subgroupCode==='HSVV'&&l.subgrupo?.codigo!=='HSVV')continue;
  if(rule.subgroupCode==='COMR'&&l.grupo?.codigo!=='COMR'&&l.subgrupo?.codigo!=='COMR')continue;
  const key=JSON.stringify([l.sistema?.codigo||null,l.grupo?.codigo||null,l.subgrupo?.codigo||null]);
  const item=collected.get(key)||{systemCode:l.sistema?.codigo||null,groupCode:l.grupo?.codigo||null,subgroupCode:l.subgrupo?.codigo||null,paths:0,models:new Set()};
  item.paths++;item.models.add(l.modelo);collected.set(key,item);
 }
 return [...collected.values()].map(v=>({...v,models:[...v.models].sort()})).sort((a,b)=>JSON.stringify([a.systemCode,a.groupCode,a.subgroupCode]).localeCompare(JSON.stringify([b.systemCode,b.groupCode,b.subgroupCode])));
}
